TITLE_FIX = {"AI globe": "AI Globe", "IceCubesApp": "Ice Cubes"}


def thumb(jpg, height=680, quality=62):
    os.makedirs(THUMBS, exist_ok=True)
    out = os.path.join(THUMBS, os.path.basename(jpg))
    if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(jpg):
        subprocess.run(["sips", "-Z", str(height), "-s", "format", "jpeg",
                        "-s", "formatOptions", str(quality), jpg, "--out", out],
                       capture_output=True)
    src = out if os.path.exists(out) else jpg
    with open(src, "rb") as f:
        return "data:image/jpeg;base64," + base64.b64encode(f.read()).decode()


def pretty(name):
    n = name.split("/")[-1]
    n = TITLE_FIX.get(n, n)
    if " " in n:
        return n[0].upper() + n[1:]
    n = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", n)
    n = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", " ", n)
    return n.replace("_", " ").strip()


def build():
    res = json.load(open(os.path.join(ROOT, "results.json")))
    cat = {e["id"]: e for e in json.load(open(os.path.join(ROOT, "catalog.json")))}
    ok = [v for v in res.values() if v["status"] == "ok" and v.get("shot")]
    bad = [v for v in res.values() if v["status"] != "ok"]

    groups = {}
    for v in ok:
        groups.setdefault(v["repo"], []).append(v)
    for g in groups.values():
        g.sort(key=lambda v: v["id"])
    order = sorted(groups, key=lambda r: (-len(groups[r]), r))
    # keep the headline single-demo repos near the top
    order.sort(key=lambda r: (0 if len(groups[r]) == 1 and r in BLURB else 1, -len(groups[r]), r))

    total_secs = sum(v.get("build_secs", 0) for v in res.values())
    cards_html = []
    for repo in order:
        items = groups[repo]
        slug = items[0]["slug"]
        cards = []
        for v in items:
            src = thumb(os.path.join(ROOT, v["shot"]))
            min_ios = v.get("min_ios") or "\u2014"
            cmd = v.get("cmd") or f'./bin/deck run "{v["id"]}"' 
            cards.append(f"""
      <figure class="card" data-name="{html.escape(v['id'].lower())}">
        <div class="screen"><img loading="lazy" src="{src}" alt="{html.escape(pretty(v['id']))} running in the simulator"></div>
        <figcaption>
          <h3>{html.escape(pretty(v['id']))}</h3>
          <div class="cardmeta"><span>iOS {html.escape(str(min_ios))}</span><span>{v.get('build_secs', 0):.0f}s build</span></div>
          <button class="cmd" data-copy="{html.escape(cmd)}">{html.escape(cmd.replace('./bin/', ''))}</button>
        </figcaption>
      </figure>""")
        cards_html.append(f"""
  <section class="group" data-repo="{html.escape(repo.lower())}">
    <div class="grouphead">
      <h2>{html.escape(repo)}</h2>
      <p>{html.escape(BLURB.get(repo, ''))}</p>
      <a class="ghlink" href="https://github.com/{html.escape(slug)}">github.com/{html.escape(slug)} ↗</a>
      <span class="n">{len(items)}</span>
    </div>
    <div class="grid">{''.join(cards)}
    </div>
  </section>""")

    fail_rows = "".join(
        f"<tr><td>{html.escape(v['id'])}</td><td>{html.escape((v.get('error') or '')[:150])}</td></tr>"
        for v in sorted(bad, key=lambda v: v["id"]))
    fail_block = f"""
  <section class="group" id="failures">
    <div class="grouphead"><h2>Didn't build</h2><p>Left in place — the source still reads fine.</p><span class="n">{len(bad)}</span></div>
    <div class="tablewrap"><table><thead><tr><th>Demo</th><th>Reason</th></tr></thead><tbody>{fail_rows}</tbody></table></div>
  </section>""" if bad else ""

    runnable = sum(1 for e in cat.values() if e["is_app"] and e["ios"])
    # str.format() is unusable here: the template is mostly CSS, which is all braces.
    fields = {
        "n_ok": len(ok),
        "n_repos": len(groups),
        "n_attempted": len(res),
        "minutes": round(total_secs / 60),
        "n_catalog": runnable - len(ok),
        "sections": "".join(cards_html),
        "failures": fail_block,
        "filters": "".join(
            f'<button class="chip" data-repo="{html.escape(r.lower())}">{html.escape(r)} <i>{len(groups[r])}</i></button>'
            for r in order),
    }
    page = TEMPLATE
    for k, v in fields.items():
        page = page.replace("{{" + k + "}}", str(v))
    # Emit pure ASCII with numeric character references. The page has to render the same
    # whether it is opened from disk, served by a bare static server that sends no charset,
    # or published as an Artifact — escaping removes the guesswork.
    page = page.encode("ascii", "xmlcharrefreplace").decode("ascii")
    with open(OUT, "w", encoding="ascii") as f:
        f.write(page)
    print(f"wrote {OUT}  ({len(ok)} screenshots, {os.path.getsize(OUT)/1e6:.1f} MB)")


